// Regenerate the neutral host regression fixture through the actual point,
// route and abandonment producers. No host data or credential files are read.
func TestWriteNativeRouteWithdrawalFixture(t *testing.T) {
	if os.Getenv("BRINE_WRITE_NATIVE_WITHDRAWAL_FIXTURE") != "1" {
		t.Skip("fixture generation not requested")
	}
	fixture := newNativeAbandonFixture(t, true)
	cap, observed := fixture.open(t)
	if _, err := fixture.state.CompleteNativeAbandonment(t.Context(), cap, observed); err != nil {
		t.Fatal(err)
	}
	if err := cap.Close(); err != nil {
		t.Fatal(err)
	}
	tables, err := fixture.state.db.QueryContext(t.Context(), "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' AND name NOT IN ('schema_version','transitions') ORDER BY rowid")
	if err != nil {
		t.Fatal(err)
	}
	names := []string{}
	for tables.Next() {
		var name string
		if err := tables.Scan(&name); err != nil {
			t.Fatal(err)
		}
		names = append(names, name)
	}
	if err := tables.Close(); err != nil {
		t.Fatal(err)
	}
	var result strings.Builder
	result.WriteString("-- Generated by TestWriteNativeRouteWithdrawalFixture from synthetic Store producers.\nPRAGMA foreign_keys=OFF;\n")
	for _, name := range names {
		writeNativeRouteFixtureTable(t, &result, fixture.state, name)
	}
	result.WriteString("PRAGMA foreign_keys=ON;\n")
	if err := os.WriteFile("../host/testdata/native-withdrawal.sql", []byte(result.String()), 0600); err != nil {
		t.Fatal(err)
	}
}

func writeNativeRouteFixtureTable(t *testing.T, result *strings.Builder, state *Store, name string) {
	t.Helper()
	columns, err := state.db.QueryContext(t.Context(), "SELECT name FROM pragma_table_info(?) ORDER BY cid", name)
	if err != nil {
		t.Fatal(err)
	}
	quotes := []string{}
	for columns.Next() {
		var column string
		if err := columns.Scan(&column); err != nil {
			t.Fatal(err)
		}
		quotes = append(quotes, "quote("+column+")")
	}
	if err := columns.Close(); err != nil {
		t.Fatal(err)
	}
	// #nosec G202 -- identifiers come from this fixture's Store schema; SQLite quote() encodes every value.
	rows, err := state.db.QueryContext(t.Context(), "SELECT "+strings.Join(quotes, ",")+" FROM "+name+" ORDER BY rowid")
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = rows.Close() }()
	for rows.Next() {
		values := make([]string, len(quotes))
		destinations := make([]any, len(values))
		for i := range values {
			destinations[i] = &values[i]
		}
		if err := rows.Scan(destinations...); err != nil {
			t.Fatal(err)
		}
		fmt.Fprintf(result, "INSERT INTO %s VALUES(%s);\n", name, strings.Join(values, ","))
	}
	if err := rows.Err(); err != nil {
		t.Fatal(err)
	}
}
